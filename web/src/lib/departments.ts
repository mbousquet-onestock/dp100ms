/** Nearest region of a coordinate, using department centroids. */
export function regionOf(lat: number, lon: number): string {
  let best = '';
  let bestD = Infinity;
  for (const [region, depts] of Object.entries(REGIONS)) {
    for (const d of depts) {
      const c = DEPARTMENT_CENTROIDS[d];
      if (!c) continue;
      const dist = (c[0] - lat) ** 2 + ((c[1] - lon) * Math.cos((lat * Math.PI) / 180)) ** 2;
      if (dist < bestD) {
        bestD = dist;
        best = region;
      }
    }
  }
  return best;
}
