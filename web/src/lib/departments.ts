/** Department code of a French postal code ("20" for Corsica, null otherwise). */
export function departmentOf(postalCode: string): string | null {
  const pc = postalCode.trim();
  if (!/^\d{5}$/.test(pc)) return null;
  const d = pc.slice(0, 2);
  if (d === '20') return '20';
  return DEPARTMENT_CENTROIDS[d] ? d : null;
}

export function customerLocation(postalCode: string): [number, number] | null {
  const d = departmentOf(postalCode);
  return d ? DEPARTMENT_CENTROIDS[d] : null;
}

