// Command benchreport turns the k6 JSON summaries of bench/results into a
// Markdown performance report. It never edits numbers: every value comes
// from the k6 output files (failed and slow requests included).
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"
)

type values map[string]float64

type metric struct {
	Values values `json:"values"`
}

type result struct {
	Meta struct {
		Name     string `json:"name"`
		VUs      int    `json:"vus"`
		Duration string `json:"duration"`
		Rate     int    `json:"rate"`
		BaseURL  string `json:"baseUrl"`
		Baskets  int    `json:"baskets"`
	} `json:"meta"`
	Metrics map[string]metric `json:"metrics"`
	Server  struct {
		CPUPct            float64 `json:"cpuPct"`
		CPUCoresUsed      float64 `json:"cpuCoresUsed"`
		GOMAXPROCS        int     `json:"gomaxprocs"`
		HeapMbAfter       float64 `json:"heapMbAfter"`
		RouteCacheHitRate float64 `json:"routeCacheHitRate"`
	} `json:"server"`
}

func (r result) v(metric, key string) float64 { return r.Metrics[metric].Values[key] }

func main() {
	in := flag.String("in", "bench/results", "k6 results directory")
	out := flag.String("out", "docs/PERFORMANCE.md", "report path")
	flag.Parse()
	files, _ := filepath.Glob(filepath.Join(*in, "*.json"))
	var results []result
	var env map[string]any
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			log.Fatal(err)
		}
		if filepath.Base(f) == "baskets.json" {
			continue
		}
		if filepath.Base(f) == "environment.json" {
			_ = json.Unmarshal(b, &env)
			continue
		}
		var r result
		if err := json.Unmarshal(b, &r); err != nil {
			log.Printf("skip %s: %v", f, err)
			continue
		}
		if r.Meta.Name == "" {
			continue
		}
		results = append(results, r)
	}
	if len(results) == 0 {
		log.Fatalf("no k6 result in %s: run `make benchmark` first", *in)
	}
	sort.Slice(results, func(i, j int) bool {
		ri, rj := results[i], results[j]
		if (ri.Meta.Rate > 0) != (rj.Meta.Rate > 0) {
			return ri.Meta.Rate == 0
		}
		if ri.Meta.Rate != rj.Meta.Rate {
			return ri.Meta.Rate < rj.Meta.Rate
		}
		return ri.Meta.VUs < rj.Meta.VUs
	})

	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("# Performance report\n\n")
	w("Generated by `make benchmark-report` on %s from the k6 summaries in `%s`. ", time.Now().UTC().Format("2006-01-02 15:04 MST"), *in)
	w("All numbers come from those files; failed and slow requests are included in every statistic.\n\n")
	w("**Target**: P95 of `POST /api/v1/delivery-promises` strictly below 100 ms, measured client-side by k6 (`http_req_duration`: request sent → last response byte, JSON serialisation included, keep-alive connections, loopback network).\n\n")
	if env != nil {
		w("## Environment\n\n| Item | Value |\n|---|---|\n")
		for _, k := range []string{"date", "cpuModel", "cpus", "memTotalMb", "kernel", "k6", "k6Cpus", "serverCpus", "baseUrl"} {
			if v, ok := env[k]; ok {
				w("| %s | %v |\n", k, v)
			}
		}
		if srv, ok := env["server"].(map[string]any); ok {
			w("| server Go | %v |\n| server GOMAXPROCS | %v |\n| server heap at start (MB) | %v |\n", srv["goVersion"], srv["gomaxprocs"], srv["heapAllocMb"])
		}
		if h, ok := env["health"].(map[string]any); ok {
			w("| dataset | seed %v, %v stock lines, persistence=%v, platform=%v |\n", h["seed"], h["stockLines"], h["persistence"], h["platform"])
		}
		w("\n")
	}
	w("## Results\n\n")
	w("| Scenario | Model | Requests | RPS | P50 ms | P90 ms | P95 ms | P99 ms | Max ms | Failed | Dropped | Engine avg ms | Server CPU | Route cache hit | P95 < 100 ms |\n")
	w("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|:---:|\n")
	pass, total := 0, 0
	for _, r := range results {
		model := fmt.Sprintf("%d VUs closed loop", r.Meta.VUs)
		if r.Meta.Rate > 0 {
			model = fmt.Sprintf("%d req/s open (max %d VUs)", r.Meta.Rate, r.Meta.VUs)
		}
		p95 := r.v("http_req_duration", "p(95)")
		failed := r.v("http_req_failed", "rate")
		ok := p95 < 100 && failed < 0.01
		total++
		mark := "no"
		if ok {
			pass++
			mark = "yes"
		}
		w("| %s | %s | %.0f | %.1f | %.2f | %.2f | %.2f | %.2f | %.2f | %.2f%% | %.0f | %.3f | %.0f%% (%.2f cores) | %.4f | %s |\n",
			r.Meta.Name, model, r.v("http_reqs", "count"), r.v("http_reqs", "rate"),
			r.v("http_req_duration", "med"), r.v("http_req_duration", "p(90)"), p95, r.v("http_req_duration", "p(99)"), r.v("http_req_duration", "max"),
			failed*100, r.v("dropped_iterations", "count"), r.v("engine_calculation_ms", "avg"),
			r.Server.CPUPct, r.Server.CPUCoresUsed, r.Server.RouteCacheHitRate, mark)
	}
	w("\n%d / %d scenarios meet the target (P95 < 100 ms and < 1%% failed requests).\n\n", pass, total)
	w("## Latency by basket category (P95, ms)\n\n| Scenario | mono | multi (single source possible) | multi-source | consolidation |\n|---|---:|---:|---:|---:|\n")
	for _, r := range results {
		w("| %s | %s | %s | %s | %s |\n", r.Meta.Name, f2(r, "latency_mono"), f2(r, "latency_multi"), f2(r, "latency_multi_source"), f2(r, "latency_consolidation"))
	}
	w("\n## Response content\n\n| Scenario | Options per response (avg) | Responses without option | Consolidated responses |\n|---|---:|---:|---:|\n")
	for _, r := range results {
		w("| %s | %.2f | %.2f%% | %.0f |\n", r.Meta.Name, r.v("options_per_response", "avg"), r.v("responses_without_option", "rate")*100, r.v("consolidated_options", "count"))
	}
	w("\n")
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		log.Fatal(err)
	}
	existing, _ := os.ReadFile(*out)
	content := b.String()
	// keep a hand-written analysis section if present
	if i := strings.Index(string(existing), "<!-- analysis -->"); i >= 0 {
		content += string(existing[i:])
	} else {
		content += "<!-- analysis -->\n## Analysis\n\n_Add the interpretation of the results here; this section is preserved by `make benchmark-report`._\n"
	}
	if err := os.WriteFile(*out, []byte(content), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s (%d scenarios)", *out, len(results))
}

func f2(r result, m string) string {
	v, ok := r.Metrics[m]
	if !ok {
		return "-"
	}
	return strconv.FormatFloat(v.Values["p(95)"], 'f', 2, 64)
}
