#!/usr/bin/env bash
# Runs the reference k6 matrix against BASE_URL and stores JSON summaries in
# bench/results/. Each scenario records server CPU time and route cache
# counters (from /api/v1/metrics and /api/v1/dashboard) before and after.
#
#   BASE_URL=http://localhost:8080 ./bench/run.sh
#   QUICK=1 ./bench/run.sh            # 10 s per scenario, fewer scenarios
#   K6_CPUS=2,3 ./bench/run.sh        # pin k6 to CPUs (taskset)
set -euo pipefail
cd "$(dirname "$0")"
BASE_URL=${BASE_URL:-http://localhost:8080}
DURATION=${DURATION:-30s}
[[ -n "${QUICK:-}" ]] && DURATION=10s
RESULTS=results
mkdir -p "$RESULTS"

K6=(k6)
if ! command -v k6 >/dev/null 2>&1; then
  K6=(docker run --rm -i --network host -v "$PWD:/bench" -w /bench grafana/k6:0.54.0)
fi
PIN=()
if [[ -n "${K6_CPUS:-}" ]] && command -v taskset >/dev/null; then PIN=(taskset -c "$K6_CPUS"); fi

curl -fsS "$BASE_URL/api/v1/health" >/dev/null || { echo "API not reachable at $BASE_URL" >&2; exit 1; }

# environment description for the report
{
  echo "{"
  echo "  \"date\": \"$(date -u +%Y-%m-%dT%H:%M:%SZ)\","
  echo "  \"baseUrl\": \"$BASE_URL\","
  echo "  \"cpuModel\": \"$( (grep -m1 'model name' /proc/cpuinfo 2>/dev/null || echo 'model name: unknown') | cut -d: -f2 | xargs)\","
  echo "  \"cpus\": $(nproc 2>/dev/null || echo 0),"
  echo "  \"memTotalMb\": $(( $(grep MemTotal /proc/meminfo 2>/dev/null | awk '{print $2}' || echo 0) / 1024 )),"
  echo "  \"kernel\": \"$(uname -sr)\","
  echo "  \"k6\": \"$("${K6[@]}" version 2>/dev/null | head -1 | sed 's/"/\\"/g')\","
  echo "  \"k6Cpus\": \"${K6_CPUS:-all}\","
  echo "  \"serverCpus\": \"${SERVER_CPUS:-unknown}\","
  echo "  \"server\": $(curl -fsS "$BASE_URL/api/v1/metrics" | python3 -c 'import json,sys; print(json.dumps(json.load(sys.stdin)["system"]))'),"
  echo "  \"health\": $(curl -fsS "$BASE_URL/api/v1/health")"
  echo "}"
} > "$RESULTS/environment.json"

# basket pool generated by the server from the real stock (reproducible)
POOL_QUERY="count=${BASKETS:-5000}&seed=${BASKET_SEED:-1}&pctMono=${PCT_MONO:-30}&pctMulti=${PCT_MULTI:-40}&pctMultiSource=${PCT_MULTI_SOURCE:-20}&pctConsolidation=${PCT_CONSOLIDATION:-10}&skusMin=${SKUS_MIN:-2}&skusMax=${SKUS_MAX:-5}&qtyMin=${QTY_MIN:-1}&qtyMax=${QTY_MAX:-2}&spread=${SPREAD:-true}"
[[ -n "${MODES:-}" ]] && POOL_QUERY+="&modes=$MODES"
[[ -n "${POSTAL_CODES:-}" ]] && POOL_QUERY+="&postalCodes=$POSTAL_CODES"
curl -fsS "$BASE_URL/api/v1/benchmarks/baskets?$POOL_QUERY" -o "$RESULTS/baskets.json"
echo "basket pool: $(python3 -c "import json,collections;d=json.load(open('$RESULTS/baskets.json'));print(len(d), dict(collections.Counter(b['category'] for b in d)))")"

snapshot() {
  curl -fsS "$BASE_URL/api/v1/dashboard" | python3 -c '
import json,sys,time
d=json.load(sys.stdin)
print(json.dumps({"t":time.time(),"cpuSeconds":d["system"]["cpuSeconds"],"numCpu":d["system"]["numCpu"],"gomaxprocs":d["system"]["gomaxprocs"],"heapMb":d["system"]["heapAllocMb"],"routeCacheHitRate":d["routeCacheHitRate"]}))'
}

run() {
  local name=$1 vus=$2 rate=$3
  echo "== $name (vus=$vus rate=$rate duration=$DURATION)"
  local before after
  before=$(snapshot)
  "${PIN[@]}" "${K6[@]}" run --quiet -e BASE_URL="$BASE_URL" -e NAME="$name" -e VUS="$vus" -e RATE="$rate" \
    -e DURATION="$DURATION" -e OUT="$RESULTS/$name.json" -e BASKET_FILE="../$RESULTS/baskets.json" k6/promise.js || true
  after=$(snapshot)
  python3 - "$RESULTS/$name.json" "$before" "$after" <<'PY'
import json, sys
path, b, a = sys.argv[1], json.loads(sys.argv[2]), json.loads(sys.argv[3])
doc = json.load(open(path))
wall = a["t"] - b["t"]
doc["server"] = {
  "cpuPct": round((a["cpuSeconds"] - b["cpuSeconds"]) / wall / max(1, a["gomaxprocs"]) * 100, 1),
  "cpuCoresUsed": round((a["cpuSeconds"] - b["cpuSeconds"]) / wall, 2),
  "gomaxprocs": a["gomaxprocs"], "heapMbAfter": a["heapMb"], "routeCacheHitRate": a["routeCacheHitRate"],
}
json.dump(doc, open(path, "w"), indent=1)
PY
  # register the run in the application history (best effort)
  if [[ -n "${ADMIN_TOKEN:-}" ]]; then
    python3 - "$RESULTS/$name.json" "$name" "$vus" "$rate" <<'PY' | curl -fsS -o /dev/null -X POST "$BASE_URL/api/v1/benchmarks/import" -H "Authorization: Bearer $ADMIN_TOKEN" -H 'Content-Type: application/json' --data-binary @- || true
import json, sys
doc = json.load(open(sys.argv[1])); m = doc["metrics"]; d = m["http_req_duration"]["values"]
def cat(k):
    v = m.get(k, {}).get("values")
    return None if not v else {"requests": int(v.get("count", 0)), "p50Ms": v["med"], "p95Ms": v["p(95)"], "p99Ms": v["p(99)"], "maxMs": v["max"], "avgMs": v["avg"], "minMs": v["min"], "p90Ms": v["p(90)"], "errors": 0}
req = int(m["http_reqs"]["values"]["count"])
summary = {"requests": req, "errors": int(round(m["http_req_failed"]["values"]["rate"] * req)), "avgMs": d["avg"], "p50Ms": d["med"], "p90Ms": d["p(90)"], "p95Ms": d["p(95)"], "p99Ms": d["p(99)"], "maxMs": d["max"], "minMs": d["min"],
  "errorRate": m["http_req_failed"]["values"]["rate"], "rps": m["http_reqs"]["values"]["rate"], "cpuAvgPct": doc["server"]["cpuPct"], "cacheHitRate": doc["server"]["routeCacheHitRate"],
  "distinctBaskets": min(req, doc["meta"]["baskets"]), "avgComputeMs": m.get("engine_calculation_ms", {}).get("values", {}).get("avg", 0),
  "droppedIterations": int(m.get("dropped_iterations", {}).get("values", {}).get("count", 0)),
  "byCategory": {k: v for k, v in {"mono": cat("latency_mono"), "multi": cat("latency_multi"), "multi-source": cat("latency_multi_source"), "consolidation": cat("latency_consolidation")}.items() if v}}
print(json.dumps({"source": "k6", "status": "completed", "config": {"name": "k6 " + sys.argv[2], "profile": sys.argv[2], "vus": int(sys.argv[3]), "rateRps": int(sys.argv[4]), "target": "http"}, "summary": summary, "series": []}))
PY
  fi
}

if [[ -n "${QUICK:-}" ]]; then
  run vus-10 10 0
  run vus-100 100 0
  run rate-500 400 500
else
  for v in 10 50 100 250 500 1000; do run "vus-$v" "$v" 0; done
  for r in 250 500 1000 1500 2000; do run "rate-$r" 1000 "$r"; done
fi
echo "results in bench/$RESULTS — run 'make benchmark-report'"
